#!/usr/bin/env node
/**
 * Writes the per-locale message chunks that lazy boundaries fetch on demand.
 *
 * `FavoritesSection` renders `ParkCard`/`AttractionCard`, so it needs the `parks`
 * (10.6 KB) and `attractions` (6.2 KB) namespaces — but it renders nothing at
 * all until the visitor has favorites, which is cookie-gated and client-only.
 * On `/blog`, `/blog/tag/…`, `/blog/authors/…`, `/blog/category/…` and
 * `/glossary/[term]` nothing else on the page needs those two namespaces, so
 * shipping them in the payload costs every visitor 16.5 KB of JSON for a section
 * that is empty for almost all of them.
 *
 * One chunk per locale, mirroring `generate-client-glossary.mjs`: a discrete
 * bundle per language means only the requested one is ever fetched.
 *
 * Output is gitignored — it is a pure derivation of `messages/<locale>.json`, so
 * committing it would only create a second copy that can drift.
 *
 * Run via `pnpm generate:message-chunks` (part of `prebuild`).
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import { LAZY_CHUNK_NAMESPACES } from '../lib/i18n/route-namespaces.mjs';

const rootDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputDir = path.join(rootDir, 'lib/i18n/message-chunks');

/** Kept in sync with `i18n/config.ts` — read from source so there is one list. */
function readLocales() {
  const source = fs.readFileSync(path.join(rootDir, 'i18n/config.ts'), 'utf-8');
  const match = source.match(/export const locales = \[([^\]]+)\]/);
  if (!match) throw new Error('Could not parse `locales` from i18n/config.ts');
  return [...match[1].matchAll(/'([^']+)'/g)].map((m) => m[1]);
}

/**
 * @param {Record<string, unknown>} messages
 * @param {readonly string[]} namespaces
 */
function pick(messages, namespaces) {
  const picked = {};
  for (const namespace of namespaces) {
    const segments = namespace.split('.');
    let source = messages;
    for (const segment of segments) {
      if (typeof source !== 'object' || source === null) {
        source = undefined;
        break;
      }
      source = source[segment];
    }
    if (source === undefined) continue;

    let target = picked;
    for (const segment of segments.slice(0, -1)) {
      const existing = target[segment];
      target[segment] = typeof existing === 'object' && existing !== null ? existing : {};
      target = target[segment];
    }
    target[segments.at(-1)] = source;
  }
  return picked;
}

/**
 * The loader resolves locales through an explicit `switch` (one static import
 * per locale, so every bundler emits a discrete chunk). That switch ends in
 * `default: en`, which means a locale added to `i18n/config.ts` but not to the
 * loader would quietly serve English card text instead of failing. `config.ts`
 * promises that adding a language is three steps and everything else follows —
 * so this asserts the loader kept up.
 *
 * @param {string[]} locales
 */
function assertLoaderCoversLocales(locales) {
  const loaderPath = path.join(rootDir, 'lib/i18n/message-chunk-loader.ts');
  const loader = fs.readFileSync(loaderPath, 'utf-8');
  const missing = locales.filter((locale) => !loader.includes(`'./message-chunks/${locale}'`));

  if (missing.length > 0) {
    throw new Error(
      `lib/i18n/message-chunk-loader.ts has no import for: ${missing.join(', ')}.\n` +
        `Add a case per locale to importLocale() — the default branch would serve ` +
        `English silently.`
    );
  }
}

async function main() {
  const locales = readLocales();
  assertLoaderCoversLocales(locales);
  fs.mkdirSync(outputDir, { recursive: true });

  const prettierConfig = await prettier.resolveConfig(path.join(outputDir, 'en.ts'));
  let totalBytes = 0;

  for (const locale of locales) {
    const messages = JSON.parse(
      fs.readFileSync(path.join(rootDir, `messages/${locale}.json`), 'utf-8')
    );
    const chunk = pick(messages, LAZY_CHUNK_NAMESPACES);
    totalBytes += Buffer.byteLength(JSON.stringify(chunk));

    const source = `// Generated by \`pnpm generate:message-chunks\` — do not edit by hand.
// Namespaces fetched on demand by a lazy boundary; see
// \`LAZY_MESSAGE_BOUNDARIES\` in \`lib/i18n/route-namespaces.mjs\`.
import type { AbstractIntlMessages } from 'next-intl';

export const MESSAGES: AbstractIntlMessages = ${JSON.stringify(chunk, null, 2)};
`;

    fs.writeFileSync(
      path.join(outputDir, `${locale}.ts`),
      await prettier.format(source, { ...prettierConfig, filepath: path.join(outputDir, 'x.ts') }),
      'utf-8'
    );
  }

  console.log(
    `✅ Generated ${locales.length} message chunks in lib/i18n/message-chunks ` +
      `(${LAZY_CHUNK_NAMESPACES.join(', ')} — avg ${Math.round(totalBytes / locales.length / 1024)} KB JSON per locale).`
  );
}

await main();
