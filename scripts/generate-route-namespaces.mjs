#!/usr/bin/env node
/**
 * Writes `i18n/route-namespaces.generated.ts` from the import graph.
 *
 * Unlike the blog/media manifests this output is COMMITTED, not gitignored: it
 * is a few hundred bytes, it is the thing a reviewer needs to see when a
 * component crosses the client boundary, and committing it keeps `next dev`
 * working on a fresh clone without a prebuild run. `pnpm check:client-messages`
 * re-derives it and fails when it has drifted, so it cannot go stale silently.
 *
 * Run via `pnpm generate:route-namespaces`, or indirectly through
 * `pnpm check:client-messages`, which tells you to run it.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import {
  analyzeRouteNamespaces,
  LAZY_MESSAGE_BOUNDARIES,
  LAZY_CHUNK_NAMESPACES,
} from '../lib/i18n/route-namespaces.mjs';

const rootDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(rootDir, 'i18n/route-namespaces.generated.ts');

/** @param {readonly string[]} list */
function formatList(list) {
  if (list.length === 0) return '[]';
  return `[\n${list.map((v) => `    '${v}',`).join('\n')}\n  ]`;
}

/**
 * Renders the generated module.
 *
 * @param {ReturnType<typeof analyzeRouteNamespaces>} analysis
 */
export function renderModule({ layout, routes, lazy }) {
  const routeEntries = Object.keys(routes)
    .sort()
    .map((key) => `  '${key}': ${formatList(routes[key])},`)
    .join('\n');

  return `// Generated by \`pnpm generate:route-namespaces\` — do not edit by hand.
// Re-run it whenever a component moves across the client boundary;
// \`pnpm check:client-messages\` fails when this file has drifted.

/**
 * Namespaces the layout chrome reads — header, footer, search, language banner.
 * Every route pays these, so they stay in the root \`NextIntlClientProvider\`.
 */
export const LAYOUT_MESSAGE_NAMESPACES = ${formatList(layout)} as const;

/**
 * What each route needs ON TOP of {@link LAYOUT_MESSAGE_NAMESPACES}.
 * An empty list means the chrome set already covers the route.
 */
export const ROUTE_MESSAGE_NAMESPACES = {
${routeEntries}
} as const;

/**
 * Namespaces fetched on demand by a lazy boundary rather than shipped in the
 * page payload (see \`LAZY_MESSAGE_BOUNDARIES\` in
 * \`lib/i18n/route-namespaces.mjs\`).
 */
export const LAZY_CHUNK_NAMESPACES = ${formatList(lazy)} as const;

export type RouteMessageKey = keyof typeof ROUTE_MESSAGE_NAMESPACES;
`;
}

/**
 * Formats with the repo's own prettier config, so a regenerated file never
 * fails `pnpm format:check` and the diff stays reviewable.
 *
 * @param {string} source
 */
export async function formatModule(source) {
  const config = await prettier.resolveConfig(outFile);
  return prettier.format(source, { ...config, filepath: outFile });
}

async function main() {
  const analysis = analyzeRouteNamespaces({ root: rootDir });
  const contents = await formatModule(renderModule(analysis));

  const previous = fs.existsSync(outFile) ? fs.readFileSync(outFile, 'utf-8') : null;
  if (previous === contents) {
    console.log('✅ i18n/route-namespaces.generated.ts already up to date.');
    return;
  }

  fs.writeFileSync(outFile, contents);

  const routeCount = Object.keys(analysis.routes).length;
  const withDelta = Object.values(analysis.routes).filter((v) => v.length > 0).length;
  console.log(
    `✅ i18n/route-namespaces.generated.ts written — ` +
      `${analysis.layout.length} layout namespaces, ${routeCount} routes ` +
      `(${routeCount - withDelta} covered by the chrome set alone), ` +
      `${LAZY_CHUNK_NAMESPACES.length} lazy via ${LAZY_MESSAGE_BOUNDARIES.length} boundary/-ies.`
  );
}

// `check-client-messages.mjs` imports `renderModule`/`formatModule` to diff the
// committed file against a fresh derivation — importing must not rewrite it.
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await main();
}
